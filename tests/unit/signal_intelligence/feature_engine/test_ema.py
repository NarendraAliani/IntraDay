def test_future_bar_does_not_influence_earlier_output() -> None:
    short_series = _series("100", "102", "104")
    longer_series = short_series + (_bar("999", offset_minutes=3),)
    definition = ExponentialMovingAverageDefinition(lookback=3)

    short_values = compute_exponential_moving_average(definition, short_series)
    longer_values = compute_exponential_moving_average(definition, longer_series)

    assert short_values[0] == longer_values[0]


def test_modifying_a_future_bar_does_not_change_earlier_ema_values() -> None:
    definition = ExponentialMovingAverageDefinition(lookback=2)
    base = _series("100", "102", "104")
    variant_a = base + (_bar("200", offset_minutes=3),)
    variant_b = base + (_bar("9999", offset_minutes=3),)

    values_a = compute_exponential_moving_average(definition, variant_a)
    values_b = compute_exponential_moving_average(definition, variant_b)

    assert values_a[:-1] == values_b[:-1]


