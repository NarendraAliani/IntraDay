# ---------------------------------------------------------------------------
# Calculation - independently hand-derived test vector (Checkpoint 16 §17)
#
#   period N = 3, alpha = 2 / (3 + 1) = 0.5, one_minus_alpha = 0.5
#   closes: 10, 20, 30, 40, 50
#   seed (mean of first 3 closes): (10 + 20 + 30) / 3 = 20   -> at bar index 2
#   EMA_4 = 0.5 * 40 + 0.5 * 20 = 20 + 10 = 30
#   EMA_5 = 0.5 * 50 + 0.5 * 30 = 25 + 15 = 40
#   expected EMA(3) series: 20, 30, 40
#
# Derived independently of the implementation under test (by hand, per the
# documented seed/recurrence rule) - not generated by calling
# compute_exponential_moving_average itself.
# ---------------------------------------------------------------------------


def test_known_3_period_ema_manually_derived_vector() -> None:
    bars = _series("10", "20", "30", "40", "50")
    definition = ExponentialMovingAverageDefinition(lookback=3)

    values = compute_exponential_moving_average(definition, bars)

    assert [v.value for v in values] == [Decimal("20"), Decimal("30"), Decimal("40")]


def test_decimal_precision_preserved_not_float() -> None:
    bars = _series("100.01", "100.02", "100.03")
    definition = ExponentialMovingAverageDefinition(lookback=3)

    values = compute_exponential_moving_average(definition, bars)

    assert len(values) == 1
    assert isinstance(values[0].value, Decimal)
    assert values[0].value == Decimal("100.02")


def test_alpha_calculation_matches_canonical_formula() -> None:
    """alpha = 2 / (N + 1); for N=4, alpha=0.4, one_minus_alpha=0.6 - a
    second, independently hand-derived vector distinct from the N=3 one."""
    bars = _series("10", "10", "10", "10", "20")  # seed=10, then one recursive step
    definition = ExponentialMovingAverageDefinition(lookback=4)

    values = compute_exponential_moving_average(definition, bars)

    # seed = mean(10,10,10,10) = 10
    # EMA_5 = 0.4*20 + 0.6*10 = 8 + 6 = 14
    assert values[0].value == Decimal("10")
    assert values[1].value == Decimal("14")


def test_recurrence_relationship_holds_for_every_post_seed_value() -> None:
    bars = _series("100", "102", "98", "105", "110", "95", "120")
    definition = ExponentialMovingAverageDefinition(lookback=3)
    alpha = Decimal(2) / Decimal(4)

    values = compute_exponential_moving_average(definition, bars)

    post_seed_bars = bars[definition.lookback :]
    for previous, current, bar in zip(values, values[1:], post_seed_bars, strict=False):
        assert current.value == alpha * bar.close + (Decimal(1) - alpha) * previous.value


def test_lookback_one_ema_equals_raw_close_series() -> None:
    """N=1 -> alpha = 2/2 = 1, one_minus_alpha = 0, so EMA_t = close_t for
    every bar, starting at the first bar (seed = mean of the first 1
    close = that close). Mathematically correct behavior, verified
    explicitly rather than special-cased in the implementation."""
    bars = _series("100", "105", "95", "110")
    definition = ExponentialMovingAverageDefinition(lookback=1)

    values = compute_exponential_moving_average(definition, bars)

    assert [v.value for v in values] == [
        Decimal("100"),
        Decimal("105"),
        Decimal("95"),
        Decimal("110"),
    ]


