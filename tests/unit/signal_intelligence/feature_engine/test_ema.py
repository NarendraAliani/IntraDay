def test_constant_price_series_ema_remains_constant() -> None:
    bars = _series("50", "50", "50", "50", "50", "50")
    definition = ExponentialMovingAverageDefinition(lookback=3)

    values = compute_exponential_moving_average(definition, bars)

    assert all(v.value == Decimal("50") for v in values)


def test_monotonically_increasing_closes_produces_deterministic_increasing_ema() -> None:
    bars = _series("10", "20", "30", "40", "50", "60")
    definition = ExponentialMovingAverageDefinition(lookback=3)

    values = compute_exponential_moving_average(definition, bars)

    # An EMA tracking a strictly increasing input series is itself
    # strictly increasing once past the seed (no false invariant is
    # assumed beyond this - e.g. it is NOT asserted to stay within any
    # arbitrary historical min/max band).
    for previous, current in zip(values, values[1:], strict=False):
        assert current.value > previous.value


def test_monotonically_decreasing_closes_produces_deterministic_decreasing_ema() -> None:
    bars = _series("60", "50", "40", "30", "20", "10")
    definition = ExponentialMovingAverageDefinition(lookback=3)

    values = compute_exponential_moving_average(definition, bars)

    for previous, current in zip(values, values[1:], strict=False):
        assert current.value < previous.value


@given(
    closes=st.lists(
        st.decimals(min_value="10", max_value="10000", places=2, allow_nan=False),
        min_size=1,
        max_size=25,
    ),
    lookback=st.integers(min_value=1, max_value=10),
)
def test_every_post_seed_value_satisfies_the_documented_recurrence(
    closes: list[Decimal], lookback: int
) -> None:
    bars = tuple(_bar(str(close), offset_minutes=i) for i, close in enumerate(closes))
    definition = ExponentialMovingAverageDefinition(lookback=lookback)
    alpha = Decimal(2) / Decimal(lookback + 1)

    values = compute_exponential_moving_average(definition, bars)

    if not values:
        return
    # Seed check: first value is the mean of the first `lookback` closes.
    assert values[0].value == sum(closes[:lookback], Decimal(0)) / lookback
    assert values[0].timestamp == bars[lookback - 1].timestamp

    # Recurrence check for every value after the seed.
    for index in range(1, len(values)):
        expected_bar = bars[lookback - 1 + index]
        expected = alpha * expected_bar.close + (Decimal(1) - alpha) * values[index - 1].value
        assert values[index].value == expected


@given(
    lookback=st.integers(min_value=1, max_value=8),
    extra=st.integers(min_value=0, max_value=5),
)
def test_first_valid_ema_occurs_exactly_at_the_documented_warm_up_point(
    lookback: int, extra: int
) -> None:
    bars = tuple(_bar(str(100 + i), offset_minutes=i) for i in range(lookback + extra))
    definition = ExponentialMovingAverageDefinition(lookback=lookback)

    values = compute_exponential_moving_average(definition, bars)

    assert len(values) == extra + 1
    assert values[0].timestamp == bars[lookback - 1].timestamp


