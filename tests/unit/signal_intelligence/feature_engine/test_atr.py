# ---------------------------------------------------------------------------
# True Range correctness - gap test (Checkpoint 17 §16)
#
# Proves True Range is NOT simply high-low: a gap where the previous
# close differs materially from the current high/low must dominate the
# calculation.
# ---------------------------------------------------------------------------


def test_true_range_captures_a_gap_not_just_high_minus_low() -> None:
    # previous bar closes at 100; current bar gaps up, trading only 104-105
    # (a narrow 1-point range) - the gap itself (5 points) must dominate.
    previous = _ohlc_bar(open_="99", high="101", low="98", close="100", offset_minutes=0)
    current = _ohlc_bar(open_="104.5", high="105", low="104", close="104.8", offset_minutes=1)
    bars = (previous, current)

    # lookback=1 so the very first TR value (bar index 1) becomes the ATR
    # seed directly - isolates the TR calculation from any smoothing.
    definition = AverageTrueRangeDefinition(lookback=1)

    values = compute_average_true_range(definition, bars)

    # high-low alone would be 105-104=1; the gap-aware TR must be 5
    # (|105 - 100|).
    assert values[0].value == Decimal("5")


