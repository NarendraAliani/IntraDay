@given(
    prices=st.lists(
        st.decimals(min_value="10", max_value="1000", places=2, allow_nan=False),
        min_size=1,
        max_size=20,
    ),
)
def test_true_range_formula_matches_canonical_definition(prices: list[Decimal]) -> None:
    bars = tuple(_flat_bar(str(price), offset_minutes=i) for i, price in enumerate(prices))
    definition = AverageTrueRangeDefinition(lookback=1)

    values = compute_average_true_range(definition, bars)

    for index, value in enumerate(values):
        previous_bar = bars[index]
        current_bar = bars[index + 1]
        expected_tr = max(
            current_bar.high - current_bar.low,
            abs(current_bar.high - previous_bar.close),
            abs(current_bar.low - previous_bar.close),
        )
        assert value.value == expected_tr


@given(
    prices=st.lists(
        st.decimals(min_value="10", max_value="1000", places=2, allow_nan=False),
        min_size=1,
        max_size=20,
    ),
    lookback=st.integers(min_value=1, max_value=6),
)
def test_wilder_recurrence_property(prices: list[Decimal], lookback: int) -> None:
    bars = tuple(_flat_bar(str(price), offset_minutes=i) for i, price in enumerate(prices))
    definition = AverageTrueRangeDefinition(lookback=lookback)

    values = compute_average_true_range(definition, bars)
    if not values:
        return

    true_ranges = [
        max(cur.high - cur.low, abs(cur.high - prev.close), abs(cur.low - prev.close))
        for prev, cur in zip(bars, bars[1:], strict=False)
    ]

    # Seed check.
    seed_window = true_ranges[:lookback]
    assert values[0].value == sum(seed_window, Decimal(0)) / lookback

    # Recurrence check for every post-seed value.
    n = Decimal(lookback)
    n_minus_1 = Decimal(lookback - 1)
    for index in range(1, len(values)):
        tr = true_ranges[lookback + index - 1]
        expected = ((values[index - 1].value * n_minus_1) + tr) / n
        assert values[index].value == expected


@given(
    lookback=st.integers(min_value=1, max_value=6),
    extra_bars=st.integers(min_value=0, max_value=5),
)
def test_warm_up_boundary_is_deterministic(lookback: int, extra_bars: int) -> None:
    total_bars = lookback + 1 + extra_bars
    bars = tuple(_flat_bar(str(100 + i), offset_minutes=i) for i in range(total_bars))
    definition = AverageTrueRangeDefinition(lookback=lookback)

    values = compute_average_true_range(definition, bars)

    assert len(values) == extra_bars + 1
    assert values[0].timestamp == bars[lookback].timestamp
