# ---------------------------------------------------------------------------
# Wilder recurrence
# ---------------------------------------------------------------------------


def test_wilder_recurrence_holds_for_every_post_seed_value() -> None:
    bars = tuple(_flat_bar(str(100 + (i % 3)), offset_minutes=i) for i in range(8))
    definition = AverageTrueRangeDefinition(lookback=3)

    values = compute_average_true_range(definition, bars)

    n = Decimal(3)
    n_minus_1 = Decimal(2)
    true_ranges = [
        max(cur.high - cur.low, abs(cur.high - prev.close), abs(cur.low - prev.close))
        for prev, cur in zip(bars, bars[1:], strict=False)
    ]
    post_seed_trs = true_ranges[definition.lookback :]
    for previous_value, current_value, tr in zip(values, values[1:], post_seed_trs, strict=False):
        expected = ((previous_value.value * n_minus_1) + tr) / n
        assert current_value.value == expected


