# ---------------------------------------------------------------------------
# Calculation - independently hand-derived test vector (Checkpoint 17 §14)
#
#   lookback N = 3
#   bar0: O=9  H=10 L=8  C=9                (supplies only the initial
#                                             previous close - produces
#                                             no TR/ATR of its own)
#   bar1: O=10 H=11 L=9  C=10 -> TR1 = max(11-9=2, |11-9|=2, |9-9|=0) = 2
#   bar2: O=11 H=12 L=10 C=11 -> TR2 = max(12-10=2, |12-10|=2, |10-10|=0) = 2
#   bar3: O=12 H=13 L=11 C=12 -> TR3 = max(13-11=2, |13-11|=2, |11-11|=0) = 2
#   seed ATR (mean of TR1..TR3) = 2, at bar3's own timestamp
#   bar4: O=13 H=14 L=9  C=13 -> TR4 = max(14-9=5, |14-12|=2, |9-12|=3) = 5
#         (previous close is bar3's close = 12)
#   ATR4 = ((2 * (3-1)) + 5) / 3 = (4 + 5) / 3 = 3
#
#   expected ATR(3) series: 2, 3
#
# Derived independently of the implementation under test (by hand, per
# the documented Wilder seed/recurrence rule) - not generated by calling
# compute_average_true_range itself.
# ---------------------------------------------------------------------------


def test_known_3_period_atr_manually_derived_vector() -> None:
    bars = (
        _ohlc_bar(open_="9", high="10", low="8", close="9", offset_minutes=0),
        _ohlc_bar(open_="10", high="11", low="9", close="10", offset_minutes=1),
        _ohlc_bar(open_="11", high="12", low="10", close="11", offset_minutes=2),
        _ohlc_bar(open_="12", high="13", low="11", close="12", offset_minutes=3),
        _ohlc_bar(open_="13", high="14", low="9", close="13", offset_minutes=4),
    )
    definition = AverageTrueRangeDefinition(lookback=3)

    values = compute_average_true_range(definition, bars)

    assert [v.value for v in values] == [Decimal("2"), Decimal("3")]
    assert values[0].timestamp == bars[3].timestamp
    assert values[1].timestamp == bars[4].timestamp


