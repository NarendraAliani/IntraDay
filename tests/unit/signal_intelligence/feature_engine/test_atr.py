RELIANCE = make_instrument_id(Exchange.NSE, "RELIANCE")
TCS = make_instrument_id(Exchange.NSE, "TCS")
START = datetime(2026, 1, 1, 3, 50, tzinfo=UTC)


def _ohlc_bar(
    *,
    open_: str,
    high: str,
    low: str,
    close: str,
    offset_minutes: int = 0,
    instrument_id: InstrumentId = RELIANCE,
    timeframe: Timeframe = Timeframe.FIVE_MINUTE,
) -> Bar:
    return Bar(
        instrument_id=instrument_id,
        timeframe=timeframe,
        timestamp=START + timedelta(minutes=5 * offset_minutes),
        open=Decimal(open_),
        high=Decimal(high),
        low=Decimal(low),
        close=Decimal(close),
        volume=Decimal("1000"),
    )


def _flat_bar(price: str, *, offset_minutes: int = 0) -> Bar:
    """A bar whose open/high/low/close are all identical - the smallest
    valid Bar (`low <= open,close <= high` trivially holds when all four
    are equal)."""
    return _ohlc_bar(open_=price, high=price, low=price, close=price, offset_minutes=offset_minutes)


