def test_future_bar_does_not_influence_earlier_output() -> None:
    short_series = tuple(_flat_bar(str(100 + i), offset_minutes=i) for i in range(4))
    longer_series = short_series + (_flat_bar("999", offset_minutes=4),)
    definition = AverageTrueRangeDefinition(lookback=3)

    short_values = compute_average_true_range(definition, short_series)
    longer_values = compute_average_true_range(definition, longer_series)

    assert short_values[0] == longer_values[0]


def test_modifying_a_future_bar_does_not_change_earlier_atr_values() -> None:
    definition = AverageTrueRangeDefinition(lookback=2)
    base = tuple(_flat_bar(str(100 + i), offset_minutes=i) for i in range(4))
    variant_a = base + (_flat_bar("200", offset_minutes=4),)
    variant_b = base + (_flat_bar("9999", offset_minutes=4),)

    values_a = compute_average_true_range(definition, variant_a)
    values_b = compute_average_true_range(definition, variant_b)

    assert values_a[:-1] == values_b[:-1]


